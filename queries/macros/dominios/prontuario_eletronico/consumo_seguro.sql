{% macro prontuario_email_autorizado(lista, email) -%}
exists (
    select 1
    from unnest(split(regexp_replace(coalesce({{ lista }}, ''), r'[;\r\n]', ','), ',')) as destinatario
    where lower(trim(destinatario)) = {{ email }}
)
{%- endmacro %}


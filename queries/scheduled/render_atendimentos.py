"""Render the standalone BigQuery scheduled query from a compiled dbt manifest."""

import argparse
import json
from pathlib import Path

# Preserve column names and order in dashboard_acolherio.dev_atendimentos.
PUBLIC_COLUMNS = """
modulo CAS TIPO_UNIDADE UNIDADE_ATENDIMENTO EMAIL_UNIDADE EMAIL_CAS
SEQ_ATENDIMENTO DATA_DE_ATENDIMENTO HORA_DE_ATENDIMENTO_ORIGINAL HORA_DE_ATENDIMENTO
ID_USUARIO ID_FAMILIA NOME_USUARIO DOCUMENTACAO NUMERO_DOCUMENTO ENDERECO
ENDERECO_NUMERO ENDERECO_COMPLEMENTO BAIRRO REFERENCIA_OU_COMUNIDADE
NOME_ATENDIMENTO_ORIGINAL DATA_NASCIMENTO IDADE RACA_COR SEXO PROFISSIONAL_ID
PROFISSIONAL PROFISSIONAL_CBO_ORIGINAL PROFISSIONAL_CBO CADASTRANTE
DATA_CADASTRO_ATENDIMENTO TIPO_ATENDIMENTO NOME_ATENDIMENTO IDADE_FAIXA
ID_ATENDIMENTO EMAIL cbo_unico_rank atendimento_unico_rank PROJETOS_SOCIAIS
""".split()


def render(manifest):
    nodes = manifest["nodes"]
    model = nodes["model.queries.int_acolherio_atendimentos"]
    sql = model["compiled_code"].strip()
    for key in sorted(model["depends_on"]["nodes"]):
        raw = nodes[key]
        if not raw["name"].startswith("raw_") or any(
            not dependency.startswith("source.") for dependency in raw["depends_on"]["nodes"]
        ):
            raise ValueError(f"Expected a raw model reading sources directly: {key}")
        relation = raw["relation_name"]
        if relation not in sql:
            raise ValueError(f"Compiled SQL does not reference {relation}")
        raw_sql = raw["compiled_code"].strip()
        sql = sql.replace(relation, f"(\n{raw_sql}\n)")
    sql = "\n".join(line.rstrip() for line in sql.splitlines())
    columns = ",\n    ".join(f"a.{name.lower()} as {name}" for name in PUBLIC_COLUMNS)
    return (
        "-- Generated by render_atendimentos.py from int_acolherio_atendimentos.\n"
        "create or replace table `rj-smas-dev.dashboard_acolherio.dev_atendimentos` as\n"
        f"select\n    {columns}\nfrom (\n{sql}\n) as a;\n"
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("manifest", type=Path)
    args = parser.parse_args()
    print(render(json.loads(args.manifest.read_text())), end="")

-- O contrato do PR é reutilizado no grão do evento, antes da agregação por usuário.
-- Não há UNNEST da equipe nem filtros de cancelamento, teste ou elegibilidade.
select
    'ATENDIMENTO' as tipo_registro,
    a.id_atendimento_modulo as id_registro_origem,
    a.id_usuario,
    a.id_familia,
    a.id_unidade,
    concat('prontuario:atendimento:', a.modulo) as origem_registro,
    date(a.data_de_atendimento) as data_evento,
    {{ inicio_mes('a.data_de_atendimento') }} as competencia,
    date(a.data_de_atendimento) as data_referencia,
    struct(
        a.modulo,
        a.seq_atendimento,
        a.id_atendimento_modulo,
        a.id_atendimento_sk,
        a.hora_de_atendimento_original,
        a.hora_de_atendimento,
        a.nome_atendimento_original,
        a.nome_atendimento,
        a.tipo_atendimento,
        a.id_tipo_atendimento,
        a.data_cadastro_atendimento,
        a.data_saida_atendimento,
        a.id_login_cadastro,
        a.cadastrante,
        a.flag_cancelado,
        a.flag_elegivel_dataviz,
        a.flag_registro_teste,
        a.flag_usuario_cadastrado,
        a.flag_unidade_cadastrada,
        a.flag_operador_cadastrado,
        a.flag_profissional_cadastrado,
        a.data_saida_vinculo_familiar,
        a.profissional_id,
        a.profissional,
        a.profissional_nome_cadastral,
        a.profissional_cbo,
        a.profissional_cbo_original,
        a.profissional_cbos,
        a.profissionais,
        a.quantidade_profissionais,
        a.flag_atendimento_compartilhado,
        a.profissionais_nomes,
        a.flag_usuario_teste,
        a.flag_unidade_teste,
        a.flag_operador_teste,
        a.flag_profissional_teste,
        a.flag_algum_profissional_teste,
        1 as cbo_unico_rank,
        (
            select p.atendimento_unico_rank from unnest(a.profissionais) as p
            where p.flag_principal)
            as atendimento_unico_rank,
        a.email,
        a.email_unidade,
        a.email_cas,
        a.email_planilha
    ) as atendimento
from {{ ref('int_atendimentos_dataviz') }} as a

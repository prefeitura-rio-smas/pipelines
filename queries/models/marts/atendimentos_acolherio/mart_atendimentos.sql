-- noqa: disable=CP02,ST06
-- Uma linha por usuário com os atendimentos da fato; filtros adicionais ficam no dataviz.
with atendimentos as (
    select evento.*
    from {{ ref('fct_atendimentos') }}
    where flag_profissional_principal
),

usuarios as (
    select
        a.ID_USUARIO,
        -- O cadastro atual é comum aos atendimentos; seleciona um perfil completo.
        array_agg(struct(
            a.NOME_USUARIO,
            a.DOCUMENTACAO,
            a.NUMERO_DOCUMENTO,
            a.ENDERECO,
            a.ENDERECO_NUMERO,
            a.ENDERECO_COMPLEMENTO,
            a.BAIRRO,
            a.REFERENCIA_OU_COMUNIDADE,
            a.DATA_NASCIMENTO,
            a.IDADE,
            a.RACA_COR,
            a.SEXO,
            a.IDADE_FAIXA,
            a.FLAG_USUARIO_CADASTRADO,
            a.FLAG_USUARIO_TESTE,
            a.VINCULOS_FAMILIARES,
            a.FLAG_POSSUI_VIOLACAO_DIREITO,
            a.VIOLACOES,
            a.VIOLACOES_DETALHES,
            a.FLAG_RECEBE_BENEFICIO,
            a.BENEFICIOS,
            a.BENEFICIOS_DETALHES,
            a.FLAG_DEFICIENCIA,
            a.DEFICIENCIAS,
            a.DEFICIENCIAS_DETALHES,
            a.FLAG_SITUACAO_RUA,
            a.FLAG_POSSUI_COMORBIDADE,
            a.COMORBIDADES,
            a.DATA_INFORMACAO_COMORBIDADES,
            a.LOCAL_TRATAMENTO_COMORBIDADES,
            a.COMORBIDADES_DETALHES
        ) order by a.ID_ATENDIMENTO_MODULO limit 1)[offset(0)] as perfil,
        array_agg(struct(
            a.modulo,
            a.CAS,
            a.TIPO_UNIDADE,
            a.UNIDADE_ATENDIMENTO,
            a.EMAIL_UNIDADE,
            a.EMAIL_CAS,
            a.SEQ_ATENDIMENTO,
            a.DATA_DE_ATENDIMENTO,
            a.HORA_DE_ATENDIMENTO_ORIGINAL,
            a.HORA_DE_ATENDIMENTO,
            a.ID_FAMILIA,
            a.NOME_ATENDIMENTO_ORIGINAL,
            a.PROFISSIONAL_ID,
            a.PROFISSIONAL,
            a.PROFISSIONAL_CBO_ORIGINAL,
            a.PROFISSIONAL_CBO,
            a.CADASTRANTE,
            a.DATA_CADASTRO_ATENDIMENTO,
            a.TIPO_ATENDIMENTO,
            a.NOME_ATENDIMENTO,
            a.ID_ATENDIMENTO,
            a.EMAIL,
            a.PROJETOS_SOCIAIS,
            a.ID_ATENDIMENTO_SK,
            a.ID_ATENDIMENTO_MODULO,
            a.ID_UNIDADE,
            a.ID_LOGIN_CADASTRO,
            a.ID_TIPO_ATENDIMENTO,
            a.FLAG_CANCELADO,
            a.DATA_SAIDA_ATENDIMENTO,
            a.DATA_SAIDA_VINCULO_FAMILIAR,
            a.PROFISSIONAL_CBOS,
            a.PROFISSIONAL_NOME_CADASTRAL,
            a.EMAIL_PLANILHA,
            a.FLAG_ELEGIVEL_DATAVIZ,
            a.FLAG_UNIDADE_CADASTRADA,
            a.FLAG_OPERADOR_CADASTRADO,
            a.FLAG_PROFISSIONAL_CADASTRADO,
            a.FLAG_UNIDADE_TESTE,
            a.FLAG_OPERADOR_TESTE,
            a.FLAG_PROFISSIONAL_TESTE,
            a.PROJETOS_SOCIAIS_HISTORICO,
            a.PROFISSIONAIS,
            a.QUANTIDADE_PROFISSIONAIS,
            a.FLAG_ALGUM_PROFISSIONAL_TESTE,
            a.PROFISSIONAIS_NOMES,
            a.FLAG_ATENDIMENTO_COMPARTILHADO,
            a.FLAG_REGISTRO_TESTE,
            a.SERVICOS_SOCIOASSISTENCIAIS,
            a.SERVICOS_SOCIOASSISTENCIAIS_HISTORICO,
            1 as cbo_unico_rank,
            (
                select p.atendimento_unico_rank
                from unnest(a.PROFISSIONAIS) as p
                where p.flag_principal
            ) as atendimento_unico_rank
        ) order by a.DATA_DE_ATENDIMENTO, a.HORA_DE_ATENDIMENTO, a.ID_ATENDIMENTO_MODULO) as ATENDIMENTOS
    from atendimentos as a
    group by a.ID_USUARIO
)

select
    ID_USUARIO,
    {{ dbt_utils.generate_surrogate_key(['ID_USUARIO']) }} as ID_USUARIO_SK,
    perfil.NOME_USUARIO,
    perfil.DOCUMENTACAO,
    perfil.NUMERO_DOCUMENTO,
    perfil.ENDERECO,
    perfil.ENDERECO_NUMERO,
    perfil.ENDERECO_COMPLEMENTO,
    perfil.BAIRRO,
    perfil.REFERENCIA_OU_COMUNIDADE,
    perfil.DATA_NASCIMENTO,
    perfil.IDADE,
    perfil.RACA_COR,
    perfil.SEXO,
    perfil.IDADE_FAIXA,
    perfil.FLAG_USUARIO_CADASTRADO,
    perfil.FLAG_USUARIO_TESTE,
    perfil.VINCULOS_FAMILIARES,
    perfil.FLAG_POSSUI_VIOLACAO_DIREITO,
    perfil.VIOLACOES,
    perfil.VIOLACOES_DETALHES,
    perfil.FLAG_RECEBE_BENEFICIO,
    perfil.BENEFICIOS,
    perfil.BENEFICIOS_DETALHES,
    perfil.FLAG_DEFICIENCIA,
    perfil.DEFICIENCIAS,
    perfil.DEFICIENCIAS_DETALHES,
    perfil.FLAG_SITUACAO_RUA,
    perfil.FLAG_POSSUI_COMORBIDADE,
    perfil.COMORBIDADES,
    perfil.DATA_INFORMACAO_COMORBIDADES,
    perfil.LOCAL_TRATAMENTO_COMORBIDADES,
    perfil.COMORBIDADES_DETALHES,
    array_length(ATENDIMENTOS) as QUANTIDADE_ATENDIMENTOS,
    ATENDIMENTOS
from usuarios
